#!/usr/bin/env python3
"""Generate ``data/vocab_key_spellings.json``: each key group's spelling.

Proposal 2a of docs/plans/vocab-tree-narrowing.md (Trello AZeJMCR3).
Every JSON key, at every depth, of an experiment's ``json_annotated``
documents is counted once per document under its group
(``vocab_canonical.group_key``) and its ``spelling_candidate``.  A
group's spelling is its most frequent candidate (ties: alphabetical),
counted in canonical space (the 2026-08-17 rule).  Groups found in
fewer than ``--min-support`` documents are left out; their keys stay
as written.

The output is git-tracked and reviewed as a diff, then shipped through
``SHARE_FILES``; changing it changes the map version records pin.

Usage::

    build_vocab_spellings --experiment production_v4_1 [--min-support 2]
"""
import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path
from typing import Any, Dict, Iterable, Iterator, Mapping, Set, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from skol_share import checkout_data_dir  # noqa: E402
from treatments_to_structured.vocab_canonical import (  # noqa: E402
    SPELLINGS_NAME,
    group_key,
    parse_annotated,
    spelling_candidate,
)

DEFAULT_MIN_SUPPORT = 2

_COMMENT = (
    'Generated by bin/build_vocab_spellings.py; review changes as a diff. '
    'Each key group (treatments_to_structured/vocab_canonical.group_key) '
    'and the spelling json_canonical writes it in: its most frequent '
    'spelling across the experiment\'s documents, counted once per '
    'document (docs/plans/vocab-tree-narrowing.md, Decisions for P2a).  '
    'Groups not listed are left as written.  Changing this file changes '
    'the map version experiment records pin (vocab_canonical.spellings).')


def _keys(value: Any) -> Iterator[str]:
    """Every key, at every depth."""
    if isinstance(value, dict):
        for key, child in value.items():
            yield str(key)
            yield from _keys(child)
    elif isinstance(value, list):
        for item in value:
            yield from _keys(item)


def _is_vocabulary(candidate: str) -> bool:
    """Leave out what cannot be a key name: no letters, or runaway text."""
    return bool(re.search(r'[A-Za-z]', candidate)) and len(candidate) <= 100


def count_spellings(docs: Iterable[Mapping[str, Any]]
                    ) -> Dict[str, Counter[str]]:
    """Per group, how many documents use each spelling candidate."""
    counts: Dict[str, Counter[str]] = defaultdict(Counter)
    for doc in docs:
        annotated = parse_annotated(doc)
        if annotated is None:
            continue
        seen: Set[Tuple[str, str]] = set()
        for raw in _keys(annotated):
            candidate = spelling_candidate(raw)
            group = group_key(raw)
            if group and _is_vocabulary(candidate):
                seen.add((group, candidate))
        for group, candidate in seen:
            counts[group][candidate] += 1
    return dict(counts)


def choose_spellings(counts: Mapping[str, Counter[str]],
                     min_support: int = DEFAULT_MIN_SUPPORT
                     ) -> Dict[str, str]:
    """Each supported group's most frequent candidate (ties:
    alphabetical).  Support is the group's total over its spellings."""
    return {group: min(c.items(), key=lambda kv: (-kv[1], kv[0]))[0]
            for group, c in counts.items()
            if c and sum(c.values()) >= min_support}


def table_text(spellings: Mapping[str, str],
               generated: Mapping[str, Any]) -> str:
    """The table file's text: deterministic, so a regeneration diffs
    cleanly."""
    return json.dumps({'_comment': _COMMENT,
                       '_generated': dict(generated),
                       'spellings': dict(sorted(spellings.items()))},
                      ensure_ascii=False, indent=1) + '\n'


def _positive_int(text: str) -> int:
    value = int(text)
    if value < 1:
        raise argparse.ArgumentTypeError(f'must be at least 1, not {value}')
    return value


def build_parser() -> argparse.ArgumentParser:
    """Strict CLI: script flags plus env_config's ``common_parser()``."""
    from env_config import common_parser

    parser = argparse.ArgumentParser(
        description='Generate data/vocab_key_spellings.json from an '
                    "experiment's json_annotated keys.",
        parents=[common_parser()],
    )
    parser.add_argument(
        '--min-support', type=_positive_int, default=DEFAULT_MIN_SUPPORT,
        help='Leave out groups found in fewer documents '
             f'(default: {DEFAULT_MIN_SUPPORT})')
    parser.add_argument(
        '--output', default=None,
        help=f"Where to write the table (default: the checkout's "
             f'data/{SPELLINGS_NAME})')
    return parser


def main() -> int:
    """Count an experiment's keys and write the table."""
    args = build_parser().parse_args()
    import couchdb
    from env_config import get_env_config

    config = get_env_config(cli_args=args)
    experiment = config.get('experiment_name')
    db_name = config.get('treatments_structured_db_name')
    if not experiment or not db_name:
        print('--experiment naming a structured treatments database is '
              'required', file=sys.stderr)
        return 2
    if args.output:
        output = Path(args.output)
    else:
        data = checkout_data_dir()
        if data is None:
            print('Not in a source checkout: pass --output', file=sys.stderr)
            return 2
        output = data / SPELLINGS_NAME

    server = couchdb.Server(config['couchdb_url'])
    server.resource.credentials = (config['couchdb_username'],
                                   config['couchdb_password'])
    db = server[db_name]
    docs = (row.doc for row in db.iterview('_all_docs', 500,
                                           include_docs=True)
            if not row.id.startswith('_design/'))
    counts = count_spellings(docs)
    spellings = choose_spellings(counts, args.min_support)
    output.write_text(table_text(spellings, {
        'experiment': experiment, 'database': db_name,
        'min_support': args.min_support, 'date': date.today().isoformat(),
    }), encoding='utf-8')
    print(f'{len(spellings):,} of {len(counts):,} groups written to '
          f'{output}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
