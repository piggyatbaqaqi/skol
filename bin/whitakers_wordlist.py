#!/usr/bin/env python3
"""Build a Latin word list from Whitaker's WORDS.

Produces the Latin vocabulary layer used by the §9 mode-B OCR
detector (``D8`` in ``docs/data_quality_production_v4_model.md``).
That detector spots OCR space-displacement by testing whether a run
of out-of-vocabulary tokens rejoins into a real word, so it is blind
to any language it has no vocabulary for — and Latin diagnoses run
79.5 % out-of-vocabulary against an English dictionary.

Source: https://github.com/mk270/whitakers-words — Col. William
Whitaker's *WORDS*, whose ``LICENCE.txt`` grants "any and all use of
program and data".  See ``data/latin_wordlist.CITATION.md``.

Two WORDS data files are read:

``DICTLINE.GEN``
    One fixed-width record per dictionary entry: four 19-character
    stem slots, a 6-character part of speech, an 18-character code
    block (declension, variant, gender…), then the five
    single-letter flags ``AGE AREA GEO FREQ SOURCE``, then the
    English definition.

``INFLECTS.LAT``
    The ending tables.  Each record ends
    ``… STEM_KEY LENGTH [ENDING] AGE FREQUENCY``; a zero LENGTH means
    the ending is empty and the ENDING token is absent.

Forms are generated by joining ``stems[STEM_KEY - 1]`` to ``ENDING``
for every inflection record matching the entry's part of speech,
declension and variant.  **A ``0`` in the INFLECTS declension or
variant column is a wildcard** — ``ADJ 1 0`` applies to every variant
of declension 1, and ``ADJ 0 0`` carries the comparative and
superlative.  Ignoring that yields 6 forms for *albus* instead of 36.

The ``AGE`` column supports restricting to newer vocabulary:

===  ==========  ==============================================
X    (default)   In use throughout the ages / unknown
A    archaic     Very early, obsolete by classical times
B    early       Pre-classical, used for effect/poetry
C    classical   ~150 BC – 200 AD
D    late        Post-classical, 3rd–5th centuries
E    later       Church/Medieval, 6th–10th
F    medieval    11th–15th centuries
G    scholar     **Post 15th, Scholarly/Scientific (16–18)**
H    modern      **Coined recently, for new things (19–20)**
===  ==========  ==============================================

Usage::

    # Everything:
    bin/whitakers_wordlist --words-dir /path/to/whitakers-words \\
        --output data/latin_wordlist.txt

    # Only post-15th-century scientific + modern vocabulary:
    bin/whitakers_wordlist --words-dir /path/to/whitakers-words \\
        --age G,H --output data/latin_wordlist_scientific.txt
"""

import argparse
import dataclasses
import sys
import unicodedata
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Set, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

_STEM_WIDTH = 19
_STEM_SLOTS = 4
_POS_START = _STEM_WIDTH * _STEM_SLOTS      # 76
_POS_WIDTH = 6
_CODE_WIDTH = 18

# Parts of speech that inflect.  ADV/PREP/CONJ/INTERJ entries carry
# their full form in the stem, and are added verbatim.
_INFLECTING = ('N', 'ADJ', 'V', 'NUM', 'PRON')

_LIGATURES = {'æ': 'ae', 'Æ': 'ae', 'œ': 'oe', 'Œ': 'oe'}

# One-letter forms are abbreviation residue.  Keeping them would let
# the D8 rejoin metric split an ordinary word at any point and still
# find both halves "known".
_MIN_LENGTH = 2

AGE_LABELS = {
    'X': 'any/unknown', 'A': 'archaic', 'B': 'early',
    'C': 'classical', 'D': 'late', 'E': 'later',
    'F': 'medieval', 'G': 'scholar (16-18C, scientific)',
    'H': 'modern (19-20C)',
}

InflectionRecord = Tuple[int, str, str]      # stem_key, ending, gender
InflectionTable = Dict[Tuple[str, str, str], List[InflectionRecord]]


@dataclasses.dataclass(frozen=True)
class Entry:
    """One DICTLINE.GEN dictionary record."""

    stems: List[str]
    pos: str
    codes: List[str]
    age: str


def parse_inflections(text: str) -> InflectionTable:
    """Parse INFLECTS.LAT into ``(pos, decl, variant)`` buckets.

    Comment lines (``--``) and blanks are skipped, as are parts of
    speech that don't inflect off a stem.
    """
    table: InflectionTable = {}
    for raw in text.splitlines():
        line = raw.split('--')[0].rstrip()
        tokens = line.split()
        if len(tokens) < 6 or tokens[0] not in _INFLECTING:
            continue
        try:
            if tokens[-3].isdigit() and int(tokens[-3]) == 0:
                stem_key, ending = int(tokens[-4]), ''
            else:
                stem_key, ending = int(tokens[-5]), tokens[-3]
        except (ValueError, IndexError):
            continue
        gender = tokens[5] if tokens[0] != 'V' else 'X'
        key = (tokens[0], tokens[1], tokens[2])
        table.setdefault(key, []).append((stem_key, ending, gender))
    return table


def endings_for(
    table: InflectionTable, pos: str, decl: str, var: str,
) -> List[InflectionRecord]:
    """Every inflection record applying to ``(pos, decl, var)``.

    A ``0`` in the INFLECTS declension or variant column is a
    wildcard, so the exact key, the variant wildcard, the declension
    wildcard and the both-wildcard key all contribute.
    """
    out: List[InflectionRecord] = []
    for d in dict.fromkeys((decl, '0')):
        for v in dict.fromkeys((var, '0')):
            out.extend(table.get((pos, d, v), []))
    return out


def parse_dictline(line: str) -> Optional[Entry]:
    """Parse one fixed-width DICTLINE.GEN record.

    Returns ``None`` for blank lines or records too short to carry a
    part of speech.
    """
    line = line.rstrip('\r\n')
    if not line.strip() or len(line) < _POS_START + _POS_WIDTH:
        return None
    stems = [
        line[i * _STEM_WIDTH:(i + 1) * _STEM_WIDTH].strip()
        for i in range(_STEM_SLOTS)
    ]
    rest = line[_POS_START:]
    pos = rest[:_POS_WIDTH].strip()
    codes = rest[_POS_WIDTH:_POS_WIDTH + _CODE_WIDTH].split()
    flags = rest[_POS_WIDTH + _CODE_WIDTH:].split()
    age = flags[0] if flags else 'X'
    if age not in AGE_LABELS:
        age = 'X'
    return Entry(stems=stems, pos=pos, codes=codes, age=age)


def forms_for_entry(entry: Entry, table: InflectionTable) -> Set[str]:
    """Every inflected form this entry generates.

    Non-inflecting parts of speech contribute their stems verbatim —
    an adverb's stem *is* the word.
    """
    if entry.pos not in _INFLECTING:
        return {s for s in entry.stems if s}
    if len(entry.codes) < 2:
        return set()
    forms: Set[str] = set()
    for stem_key, ending, _gender in endings_for(
        table, entry.pos, entry.codes[0], entry.codes[1],
    ):
        index = stem_key - 1
        if 0 <= index < len(entry.stems) and entry.stems[index]:
            forms.add(entry.stems[index] + ending)
    return forms


def fold_form(form: str) -> Optional[str]:
    """Normalise one form for set-membership use.

    Lowercases, expands ``æ``/``œ`` and strips combining marks so
    ``abscīdō`` matches ``abscido``.  Returns ``None`` for anything
    non-alphabetic after folding, or shorter than two characters.

    Folding belongs to the *word list*.  Never fold treatment text —
    rewriting it would invalidate every stored span offset.
    """
    if not form:
        return None
    for lig, repl in _LIGATURES.items():
        form = form.replace(lig, repl)
    decomposed = unicodedata.normalize('NFKD', form)
    stripped = ''.join(
        ch for ch in decomposed if not unicodedata.combining(ch)
    ).lower()
    if not stripped.isalpha() or not stripped.isascii():
        return None
    if len(stripped) < _MIN_LENGTH:
        return None
    return stripped


def build_wordlist(
    dictline: str, inflects: str, ages: Optional[Set[str]] = None,
) -> List[str]:
    """Sorted, deduplicated, folded word list.

    ``ages`` restricts to those AGE codes; ``None`` keeps everything.
    """
    table = parse_inflections(inflects)
    words: Set[str] = set()
    for line in dictline.splitlines():
        entry = parse_dictline(line)
        if entry is None:
            continue
        if ages and entry.age not in ages:
            continue
        for form in forms_for_entry(entry, table):
            folded = fold_form(form)
            if folded:
                words.add(folded)
    return sorted(words)


def _read(path: Path) -> str:
    # WORDS data files are Latin-1 with CRLF line endings.
    return path.read_text(encoding='latin-1')


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        '--words-dir', required=True, metavar='DIR',
        help='Checkout of github.com/mk270/whitakers-words, holding '
             'DICTLINE.GEN and INFLECTS.LAT.',
    )
    parser.add_argument(
        '--output', required=True, metavar='PATH',
        help='Word list to write, one folded form per line.',
    )
    parser.add_argument(
        '--age', default=None, metavar='CODES',
        help='Comma-separated AGE codes to keep, e.g. "G,H" for '
             'post-15th-century scholarly/scientific plus modern. '
             'Omit to keep every age.',
    )
    args = parser.parse_args(argv)

    words_dir = Path(args.words_dir).expanduser()
    dictline_path = words_dir / 'DICTLINE.GEN'
    inflects_path = words_dir / 'INFLECTS.LAT'
    for path in (dictline_path, inflects_path):
        if not path.is_file():
            print(f"error: {path} not found", file=sys.stderr)
            return 2

    ages: Optional[Set[str]] = None
    if args.age:
        ages = {c.strip().upper() for c in args.age.split(',') if c.strip()}
        unknown = sorted(ages - set(AGE_LABELS))
        if unknown:
            print(f"error: unknown AGE code(s) {unknown}; valid codes are "
                  f"{sorted(AGE_LABELS)}", file=sys.stderr)
            return 2

    words = build_wordlist(
        _read(dictline_path), _read(inflects_path), ages=ages,
    )
    if not words:
        print("error: no forms generated; check --age", file=sys.stderr)
        return 2

    out_path = Path(args.output).expanduser()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open('w', encoding='utf-8') as handle:
        for word in words:
            handle.write(word + '\n')

    scope = (', '.join(f'{a} ({AGE_LABELS[a]})' for a in sorted(ages))
             if ages else 'all ages')
    print(f"{len(words)} forms [{scope}] -> {out_path}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
